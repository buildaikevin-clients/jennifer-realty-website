"""Emit the finished logo asset set into the site's assets folder."""
import os
import build_logo as B
from build_logo import initials, centered, CINZ, MONT

OUT = r"c:\Claude\shared\clients\jennifer-realty-website\assets"

DEEP, BONE, INK, GULF, GULF_D = "#1f2422", "#efeeec", "#242424", "#6f9ea3", "#2c5f66"
MUTED, SAND_L = "#646260", "#bcbcba"

HEAD = ("<!-- Jennifer Barragan. Split initials mark, drawn 2026-07-28.\n"
        "     {what}, converted from Cormorant Garamond{extra} to outlined\n"
        "     paths, so the mark never depends on a webfont having loaded.\n"
        "     Colors are site tokens only: deep {d}, bone {b}, gulf {g}.\n"
        "     Regenerated by brand/build/emit.py. Do not hand edit the paths. -->\n")


def write(name, body):
    p = os.path.join(OUT, name)
    open(p, "w", encoding="utf-8").write(body)
    print(f"{name:26} {os.path.getsize(p):7,} bytes")
    return body


# ------------------------------------------------------------- the bare mark --
# Tight crop: the viewBox is the inked bounds plus a little quiet space, so the
# file drops into any box and is sized with width or height alone.
m = initials(size=100, gap=13, cx=0, baseline=0)
PAD = 3
# Rounded outward to whole units so the intrinsic size an author writes in
# markup is the exact aspect ratio, with no layout shift from a fractional box.
import math
vb = (math.floor(m["left"] - PAD), math.floor(m["top"] - PAD), 0, 0)
vb = (vb[0], vb[1],
      math.ceil(m["right"] + PAD) - vb[0], math.ceil(m["bottom"] + PAD) - vb[1])


def mark(letter, rule, label):
    return (
        HEAD.format(what="The J and B monogram", extra="", d=DEEP, b=BONE, g=GULF) +
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb[0]:g} {vb[1]:g} '
        f'{vb[2]:g} {vb[3]:g}" role="img" aria-label="{label}">\n'
        f'  <path fill="{letter}" d="{m["J"]}"/>\n'
        f'  <path stroke="{rule}" stroke-width="1.6" d="M{m["rule"]:g} '
        f'{m["top"] + 2:g} V9"/>\n'
        f'  <path fill="{letter}" d="{m["B"]}"/>\n'
        '</svg>\n')


write("logo-mark.svg", mark(INK, GULF_D, "Jennifer Barragan"))
write("logo-mark-light.svg", mark(BONE, GULF, "Jennifer Barragan"))

# --------------------------------------------------------------- the favicon --
# The mark on the deep plate, filling about three quarters of the tile so it
# survives the rounding and downscaling a browser applies to a bookmark icon.
f = initials(size=48, gap=6, cx=32, baseline=0)
dy = (64 - (f["bottom"] - f["top"])) / 2 - f["top"]   # center the ink, not the baseline
write("favicon.svg",
      HEAD.format(what="The J and B monogram on the dark plate", extra="",
                  d=DEEP, b=BONE, g=GULF) +
      '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" '
      'role="img" aria-label="Jennifer Barragan">\n'
      f'  <rect width="64" height="64" rx="8" fill="{DEEP}"/>\n'
      f'  <g transform="translate(0 {dy:.2f})">\n'
      f'    <path fill="{BONE}" d="{f["J"]}"/>\n'
      f'    <path stroke="{GULF}" stroke-width="2.2" '
      f'd="M{f["rule"]:g} {f["top"] + 1:g} V4"/>\n'
      f'    <path fill="{BONE}" d="{f["B"]}"/>\n'
      '  </g>\n</svg>\n')

# ---------------------------------------------------------------- the lockup --
L = initials(size=72, gap=28, cx=210, baseline=72)
name, name_w = centered(CINZ, "JENNIFER BARRAGAN", 15, 6.5, 210, 106)
loc, loc_w = centered(MONT, "BRADENTON FLORIDA", 9.5, 4.8, 210, 130)

# The Cinzel name line is the widest element, so it sets the box. Six units of
# clear space all round, which is the minimum the mark should ever be given.
LPAD = 6
lx = math.floor(min(L["left"], 210 - name_w / 2) - LPAD)
lw = math.ceil(max(L["right"], 210 + name_w / 2) + LPAD) - lx
ly = math.floor(L["top"] - LPAD)
lh = (130 + LPAD) - ly           # both supporting lines are caps, no descenders


def lockup(letter, rule, quiet, label):
    return (
        HEAD.format(what="The full lockup", extra=", Cinzel and Montserrat",
                    d=DEEP, b=BONE, g=GULF) +
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{lx:g} {ly:g} '
        f'{lw:g} {lh:g}" role="img" aria-label="{label}">\n'
        f'  <path fill="{letter}" d="{L["J"]}"/>\n'
        f'  <path stroke="{rule}" stroke-width="1" d="M{L["rule"]:g} '
        f'{L["top"] - 4:g} V80"/>\n'
        f'  <path fill="{letter}" d="{L["B"]}"/>\n'
        f'  <path fill="{letter}" d="{name}"/>\n'
        f'  <path fill="{quiet}" d="{loc}"/>\n'
        '</svg>\n')


ALT = "Jennifer Barragan, Bradenton Florida"
write("logo.svg", lockup(INK, GULF_D, MUTED, ALT))
write("logo-reversed.svg", lockup(BONE, GULF, SAND_L, ALT))

# -------------------------------------------------- the touch icon source ---
# iOS rounds the corners of a home screen icon itself, so this one is a full
# bleed square with no radius of its own and a little more breathing room.
# Rasterized to PNG by rasterize.sh, because Safari ignores an SVG here.
t = initials(size=42, gap=5.5, cx=32, baseline=0)
tdy = (64 - (t["bottom"] - t["top"])) / 2 - t["top"]
write("apple-touch-icon.svg",
      HEAD.format(what="Touch icon source, full bleed square", extra="",
                  d=DEEP, b=BONE, g=GULF) +
      '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="180" '
      'height="180" role="img" aria-label="Jennifer Barragan">\n'
      f'  <rect width="64" height="64" fill="{DEEP}"/>\n'
      f'  <g transform="translate(0 {tdy:.2f})">\n'
      f'    <path fill="{BONE}" d="{t["J"]}"/>\n'
      f'    <path stroke="{GULF}" stroke-width="2" '
      f'd="M{t["rule"]:g} {t["top"] + 1:g} V3.5"/>\n'
      f'    <path fill="{BONE}" d="{t["B"]}"/>\n'
      '  </g>\n</svg>\n')
